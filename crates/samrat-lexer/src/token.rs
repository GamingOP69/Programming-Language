#[derive(Debug, Clone, PartialEq)]
pub enum TokenType {
    // Conversational Keywords
    When,
    The,
    Program,
    Starts,
    Create,
    Set,
    To,
    From,
    Keep,
    Even,
    Odd,
    Add,
    Subtract,
    Multiply,
    Divide,
    Them,
    Together,
    Show,
    Print,
    Total,
    Given,
    With,
    Parameters,
    Do,
    If,
    Then,
    Else,
    Elif,
    While,
    For,
    In,
    Each,
    Return,
    Define,
    Function,
    Class,
    Struct,
    Unsafe,
    Spawn,
    Channel,
    Send,
    Receive,
    True,
    False,
    Null,
    Import,
    As,
    FromModule,
    Try,
    Catch,
    Throw,

    // Literals
    Integer(i64),
    Float(f64),
    StringLiteral(String),
    Identifier(String),

    // Symbols & Operators
    Period,
    Comma,
    Colon,
    Semicolon,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Equal,
    EqualEqual,
    NotEqual,
    LessThan,
    GreaterThan,
    LessEqual,
    GreaterEqual,
    And,
    Or,
    Not,
    Arrow,
    Dot,
    Range,

    // Layout
    Newline,
    Eof,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub token_type: TokenType,
    pub lexeme: String,
    pub line: usize,
    pub column: usize,
}

impl Token {
    pub fn new(
        token_type: TokenType,
        lexeme: impl Into<String>,
        line: usize,
        column: usize,
    ) -> Self {
        Self {
            token_type,
            lexeme: lexeme.into(),
            line,
            column,
        }
    }
}
